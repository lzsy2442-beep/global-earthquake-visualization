_DIST_RE = re.compile(
    r"^\s*(\d+)\s*km\s+([A-Z]{1,3})\s+of\s+(.+?)\s*$", re.IGNORECASE)

# 未命中词典的记录收集，便于补词典
_UNKNOWN = []


def _nautical_miles(km):
    return round(km / 1.852, 1)


def translate_place(en):
    """返回中文位置描述；无法完全处理时尽力转换并登记。"""
    if not en:
        return ""
    m = _DIST_RE.match(en)
    if m:
        km = int(m.group(1))
        d = m.group(2).upper()
        rest = m.group(3).strip()
        if "," in rest:
            name_part, suffix = rest.rsplit(",", 1)
            suffix = suffix.strip()
            country = COUNTRY_CN.get(suffix)
            if country is None:
                _UNKNOWN.append(en)
                country = suffix
            place_name = name_part.strip()
        else:
            # 无逗号后缀：整体可能是已知地名
            if rest in PLAIN_CN:
                place_name = ""
                country = PLAIN_CN[rest]
            else:
                _UNKNOWN.append(en)
                place_name = ""
                country = rest
        dir_cn = DIR_CN.get(d)
        if dir_cn is None:
            _UNKNOWN.append(en)
            dir_cn = d
        nmi = _nautical_miles(km)
        if place_name:
            return f"{country} {place_name} {dir_cn}方向 {km}公里（约{nmi}海里）"
        return f"{country} {dir_cn}方向 {km}公里（约{nmi}海里）"
    # 整体地名
    if en in PLAIN_CN:
        return PLAIN_CN[en]
    # 大小写不敏感再试一次
    low_map = {k.lower(): v for k, v in PLAIN_CN.items()}
    if en.lower() in low_map:
        return low_map[en.lower()]
    _UNKNOWN.append(en)
    return en


def unknown_items():
    return sorted(set(_UNKNOWN))
